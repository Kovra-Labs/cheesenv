//! Projects: every folder in `www/` is served as `<folder>.test` by the
//! installed web servers (PRD §4 auto virtual host).

use std::path::{Path, PathBuf};

use serde::Serialize;

use crate::error::{AppError, AppResult};
use crate::modules::InstalledModule;
use crate::paths::{write_atomic, Layout};

pub const TLD: &str = "test";
/// Folder (inside a web server's config dir) its main config includes.
const VHOST_DIR: &str = "vhosts";
/// The one file Stackyard owns there; users may add their own `*.conf` next to it.
const VHOST_FILE: &str = "stackyard-projects.conf";
/// Web servers whose vhosts Stackyard knows how to render.
pub const WEB_SERVERS: [&str; 2] = ["nginx", "apache"];

#[derive(Debug, Clone, Serialize, PartialEq)]
pub struct Project {
    pub name: String,
    /// `<name>.test`, or `None` when the folder name is not a valid DNS label.
    pub domain: Option<String>,
    pub path: String,
    /// Folder served as the web root: `public/` when present (Laravel, Symfony…).
    pub doc_root: String,
}

/// A DNS label: lowercase letters, digits and inner dashes, at most 63 chars.
pub fn is_valid_label(s: &str) -> bool {
    let b = s.as_bytes();
    !b.is_empty()
        && b.len() <= 63
        && b.iter().all(|c| c.is_ascii_lowercase() || c.is_ascii_digit() || *c == b'-')
        && b[0] != b'-'
        && b[b.len() - 1] != b'-'
}

/// `<label>.test` with a valid label: the only names Stackyard ever routes.
pub fn is_valid_domain(d: &str) -> bool {
    d.strip_suffix(TLD)
        .and_then(|l| l.strip_suffix('.'))
        .is_some_and(is_valid_label)
}

fn slash(p: &Path) -> String {
    p.to_string_lossy().replace('\\', "/")
}

pub fn list(layout: &Layout) -> Vec<Project> {
    let Ok(entries) = std::fs::read_dir(layout.www()) else { return Vec::new() };
    let mut out: Vec<Project> = entries
        .flatten()
        // Follows symlinks: linking a project from elsewhere into www/ is supported.
        .filter(|e| e.path().is_dir())
        .filter_map(|e| {
            let name = e.file_name().to_str()?.to_string();
            if name.starts_with('.') {
                return None;
            }
            let path = e.path();
            let public = path.join("public");
            let doc_root = if public.is_dir() { public } else { path.clone() };
            Some(Project {
                domain: is_valid_label(&name).then(|| format!("{name}.{TLD}")),
                path: slash(&path),
                doc_root: slash(&doc_root),
                name,
            })
        })
        .collect();
    out.sort_by(|a, b| a.name.cmp(&b.name));
    out
}

pub fn domains(projects: &[Project]) -> Vec<String> {
    projects.iter().filter_map(|p| p.domain.clone()).collect()
}

/// Creates `www/<name>` with a starter page.
pub fn create(layout: &Layout, name: &str) -> AppResult<Project> {
    if !is_valid_label(name) {
        return Err(AppError::InvalidInput(format!("project name '{name}'")));
    }
    let dir = layout.www().join(name);
    if dir.exists() {
        return Err(AppError::AlreadyExists);
    }
    std::fs::create_dir_all(&dir)?;
    let page = format!(
        "<!doctype html><html lang=\"en\"><head><meta charset=\"utf-8\"><title>{name}.{TLD}</title></head>\
<body style=\"font-family:system-ui;max-width:40rem;margin:4rem auto\"><h1>{name}.{TLD}</h1>\
<p>Edit the files in this folder to build your project.</p></body></html>\n"
    );
    std::fs::write(dir.join("index.html"), page)?;
    list(layout).into_iter().find(|p| p.name == name).ok_or_else(|| AppError::NotFound(name.into()))
}

/// Whether the installed web server's config includes the vhost folder
/// (older registry templates did not).
pub fn supports_vhosts(m: &InstalledModule) -> bool {
    WEB_SERVERS.contains(&m.name.as_str()) && m.config_templates.values().any(|t| t.contains("/vhosts/"))
}

/// `m` with the vhost include added to its main config template, for web
/// servers installed from a registry template that predates it. `None` when
/// nothing needs to change (or the template has an unknown shape).
pub fn with_vhost_include(m: &InstalledModule) -> Option<InstalledModule> {
    if !WEB_SERVERS.contains(&m.name.as_str()) || supports_vhosts(m) {
        return None;
    }
    const NOTE: &str = "# Projects (<folder>.test) generated by Stackyard, plus your own *.conf files.";
    let mut out = m.clone();
    match m.name.as_str() {
        "nginx" => {
            // The `http { … }` block closes with the template's last brace.
            let tpl = out.config_templates.get_mut("nginx.conf")?;
            let end = tpl.rfind('}')?;
            tpl.insert_str(end, &format!("\n    {NOTE}\n    include \"{{{{conf}}}}/vhosts/*.conf\";\n"));
        }
        "apache" => {
            let tpl = out.config_templates.get_mut("httpd.conf")?;
            if !tpl.ends_with('\n') {
                tpl.push('\n');
            }
            tpl.push_str(&format!("\n{NOTE}\nIncludeOptional \"{{{{conf}}}}/vhosts/*.conf\"\n"));
        }
        _ => return None,
    }
    Some(out)
}

/// Paths go inside double-quoted config strings; nginx also expands `$`.
fn check_conf_path(p: &str) -> AppResult<()> {
    if p.chars().any(|c| c == '"' || c == '$' || c.is_control()) {
        return Err(AppError::InvalidInput(format!("path not usable in web server config: {p}")));
    }
    Ok(())
}

const NGINX_FASTCGI: &str = "\
            fastcgi_param QUERY_STRING $query_string;
            fastcgi_param REQUEST_METHOD $request_method;
            fastcgi_param CONTENT_TYPE $content_type;
            fastcgi_param CONTENT_LENGTH $content_length;
            fastcgi_param SCRIPT_NAME $fastcgi_script_name;
            fastcgi_param SCRIPT_FILENAME $document_root$fastcgi_script_name;
            fastcgi_param PATH_INFO $fastcgi_path_info;
            fastcgi_param REQUEST_URI $request_uri;
            fastcgi_param DOCUMENT_URI $document_uri;
            fastcgi_param DOCUMENT_ROOT $document_root;
            fastcgi_param SERVER_PROTOCOL $server_protocol;
            fastcgi_param REQUEST_SCHEME $scheme;
            fastcgi_param HTTPS $https if_not_empty;
            fastcgi_param GATEWAY_INTERFACE CGI/1.1;
            fastcgi_param SERVER_SOFTWARE nginx/$nginx_version;
            fastcgi_param REMOTE_ADDR $remote_addr;
            fastcgi_param REMOTE_PORT $remote_port;
            fastcgi_param SERVER_ADDR $server_addr;
            fastcgi_param SERVER_PORT $server_port;
            fastcgi_param SERVER_NAME $server_name;
            fastcgi_param REDIRECT_STATUS 200;
            fastcgi_param HTTP_PROXY \"\";
";

/// A project with the PHP-FPM port its `.php` files go to.
#[derive(Debug, Clone)]
pub struct Site {
    pub project: Project,
    pub php_port: Option<u16>,
}

/// HTTPS for a web server's project vhosts.
pub struct Tls {
    pub port: u16,
    pub cert: String,
    pub key: String,
}

/// The HTTPS port paired with an HTTP port: 80 → 443, 8080 → 8443.
pub fn https_port(http: u16) -> Option<u16> {
    http.checked_add(363)
}

fn render_nginx(sites: &[Site], port: u16, tls: Option<&Tls>) -> String {
    let mut out = String::from("# Generated by Stackyard from the www/ folder; changes are overwritten.\n");
    for Site { project: p, php_port } in sites {
        let Some(domain) = &p.domain else { continue };
        let fallback = if php_port.is_some() { "/index.php?$query_string" } else { "=404" };
        out.push_str(&format!("\nserver {{\n    listen 127.0.0.1:{port};\n"));
        if let Some(t) = tls {
            out.push_str(&format!(
                "    listen 127.0.0.1:{} ssl;\n    http2 on;\n    ssl_certificate \"{}\";\n    ssl_certificate_key \"{}\";\n",
                t.port, t.cert, t.key
            ));
        }
        out.push_str(&format!(
            "    server_name {domain};\n    root \"{}\";\n    index index.php index.html index.htm;\n    charset utf-8;\n\n    location / {{\n        try_files $uri $uri/ {fallback};\n    }}\n\n    location ~ /\\.(?!well-known) {{\n        deny all;\n    }}\n",
            p.doc_root
        ));
        if let Some(php) = php_port {
            out.push_str(&format!(
                "\n    location ~ \\.php$ {{\n        fastcgi_split_path_info ^(.+\\.php)(/.+)$;\n        try_files $fastcgi_script_name =404;\n        fastcgi_pass 127.0.0.1:{php};\n        fastcgi_index index.php;\n{NGINX_FASTCGI}    }}\n"
            ));
        }
        out.push_str("}\n");
    }
    out
}

fn render_apache(sites: &[Site], port: u16, www: &str) -> String {
    let mut out = String::from("# Generated by Stackyard from the www/ folder; changes are overwritten.\n");
    if sites.iter().all(|s| s.project.domain.is_none()) {
        return out;
    }
    // The first vhost of an address answers unknown names: keep that `localhost`.
    out.push_str(&format!(
        "\n<VirtualHost 127.0.0.1:{port}>\n    ServerName localhost\n    DocumentRoot \"{www}\"\n</VirtualHost>\n"
    ));
    for Site { project: p, php_port } in sites {
        let Some(domain) = &p.domain else { continue };
        // Project folders sit under www/, whose <Directory> rules (AllowOverride
        // All) come from the main config; the project's PHP version overrides
        // the main config's handler.
        out.push_str(&format!(
            "\n<VirtualHost 127.0.0.1:{port}>\n    ServerName {domain}\n    DocumentRoot \"{}\"\n    <LocationMatch \"/\\.(?!well-known)\">\n        Require all denied\n    </LocationMatch>\n",
            p.doc_root
        ));
        if let Some(php) = php_port {
            out.push_str(&format!(
                "    <FilesMatch \"\\.php$\">\n        SetHandler \"proxy:fcgi://127.0.0.1:{php}\"\n    </FilesMatch>\n"
            ));
        }
        out.push_str("</VirtualHost>\n");
    }
    out
}

pub fn vhost_file(layout: &Layout, m: &InstalledModule) -> PathBuf {
    layout.conf_dir(&m.name, &m.version).join(VHOST_DIR).join(VHOST_FILE)
}

/// Writes the vhost file of web server `m` (listening on `port`; nginx also
/// serves HTTPS with `tls`). Returns whether its content changed, i.e.
/// whether a running server must restart.
pub fn write_vhosts(layout: &Layout, m: &InstalledModule, port: u16, tls: Option<&Tls>, sites: &[Site]) -> AppResult<bool> {
    let www = slash(&layout.www());
    check_conf_path(&www)?;
    let tls = match tls {
        Some(t) if check_conf_path(&t.cert).is_ok() && check_conf_path(&t.key).is_ok() => Some(t),
        _ => None,
    };
    let usable: Vec<Site> = sites.iter().filter(|s| check_conf_path(&s.project.doc_root).is_ok()).cloned().collect();
    let content = match m.name.as_str() {
        "nginx" => render_nginx(&usable, port, tls),
        "apache" => render_apache(&usable, port, &www),
        _ => return Ok(false),
    };
    let file = vhost_file(layout, m);
    if std::fs::read_to_string(&file).is_ok_and(|old| old == content) {
        return Ok(false);
    }
    if let Some(dir) = file.parent() {
        std::fs::create_dir_all(dir)?;
    }
    write_atomic(&file, content.as_bytes())?;
    Ok(true)
}

#[cfg(test)]
mod tests {
    use super::*;
    use std::collections::BTreeMap;

    fn web(name: &str, tpl: &str) -> InstalledModule {
        InstalledModule {
            name: name.into(),
            version: "1.0.0".into(),
            category: "web-server".into(),
            bin_dir: String::new(),
            service: None,
            config_templates: BTreeMap::from([("main.conf".into(), tpl.into())]),
            panel: None,
            shims: BTreeMap::new(),
            installed_at: 0,
        }
    }

    #[test]
    fn labels_and_domains() {
        for ok in ["toko", "my-app", "a1", "x"] {
            assert!(is_valid_label(ok), "{ok}");
        }
        for bad in ["", "-a", "a-", "Toko", "my app", "a.b", "../x", &"a".repeat(64)] {
            assert!(!is_valid_label(bad), "{bad}");
        }
        assert!(is_valid_domain("toko.test"));
        assert!(!is_valid_domain("toko.com"));
        assert!(!is_valid_domain("evil.com.test.test"));
        assert!(!is_valid_domain(".test"));
        assert!(!is_valid_domain("bank.com\n127.0.0.1 x.test"));
    }

    #[test]
    fn lists_projects_with_public_root_and_skips_invalid_domains() {
        let tmp = tempfile::tempdir().unwrap();
        let layout = Layout::new(tmp.path().to_path_buf());
        layout.ensure().unwrap();
        std::fs::create_dir_all(layout.www().join("shop/public")).unwrap();
        std::fs::create_dir_all(layout.www().join("My Site")).unwrap();
        std::fs::create_dir_all(layout.www().join(".git")).unwrap();
        create(&layout, "blog").unwrap();
        #[cfg(unix)]
        std::os::unix::fs::symlink(tmp.path().join("www/shop"), layout.www().join("linked")).unwrap();
        assert!(matches!(create(&layout, "blog"), Err(AppError::AlreadyExists)));
        assert!(create(&layout, "Bad Name").is_err());

        let ps = list(&layout);
        let names: Vec<_> = ps.iter().map(|p| p.name.as_str()).collect();
        #[cfg(unix)]
        assert_eq!(names, ["My Site", "blog", "linked", "shop"]);
        assert_eq!(ps[0].domain, None);
        assert!(ps.last().unwrap().doc_root.ends_with("/shop/public"));
        assert!(domains(&ps).contains(&"blog.test".to_string()));
    }

    #[test]
    fn vhosts_render_and_report_changes() {
        let tmp = tempfile::tempdir().unwrap();
        let layout = Layout::new(tmp.path().to_path_buf());
        layout.ensure().unwrap();
        create(&layout, "toko").unwrap();
        let ps = list(&layout);
        let nginx = web("nginx", "include \"{{conf}}/vhosts/*.conf\";");
        assert!(supports_vhosts(&nginx));
        assert!(!supports_vhosts(&web("nginx", "server {}")));

        let sites = |php: Option<u16>| ps.iter().map(|p| Site { project: p.clone(), php_port: php }).collect::<Vec<_>>();
        assert!(write_vhosts(&layout, &nginx, 8080, None, &sites(Some(9000))).unwrap());
        assert!(!write_vhosts(&layout, &nginx, 8080, None, &sites(Some(9000))).unwrap(), "unchanged");
        let conf = std::fs::read_to_string(vhost_file(&layout, &nginx)).unwrap();
        assert!(conf.contains("server_name toko.test;"));
        assert!(conf.contains("listen 127.0.0.1:8080;"));
        assert!(conf.contains("fastcgi_pass 127.0.0.1:9000;"));
        assert!(!conf.contains("ssl"));
        assert!(write_vhosts(&layout, &nginx, 8080, None, &sites(None)).unwrap(), "php removed");
        assert!(!std::fs::read_to_string(vhost_file(&layout, &nginx)).unwrap().contains("fastcgi_pass"));

        let tls = Tls { port: https_port(8080).unwrap(), cert: "/c/projects.pem".into(), key: "/c/projects-key.pem".into() };
        assert!(write_vhosts(&layout, &nginx, 8080, Some(&tls), &sites(Some(9083))).unwrap());
        let conf = std::fs::read_to_string(vhost_file(&layout, &nginx)).unwrap();
        assert!(conf.contains("listen 127.0.0.1:8443 ssl;"), "{conf}");
        assert!(conf.contains("ssl_certificate_key \"/c/projects-key.pem\";"));
        assert!(conf.contains("fastcgi_pass 127.0.0.1:9083;"));
        assert_eq!(https_port(80), Some(443));

        let apache = web("apache", "IncludeOptional \"{{conf}}/vhosts/*.conf\"");
        write_vhosts(&layout, &apache, 8082, Some(&tls), &sites(Some(9083))).unwrap();
        let conf = std::fs::read_to_string(vhost_file(&layout, &apache)).unwrap();
        assert!(conf.contains("SetHandler \"proxy:fcgi://127.0.0.1:9083\""), "per-project PHP");
        assert!(!conf.contains("ssl"), "Apache: HTTP only");
        let first = conf.find("ServerName localhost").unwrap();
        assert!(first < conf.find("ServerName toko.test").unwrap(), "localhost stays the default vhost");
        assert!(conf.contains("<LocationMatch \"/\\.(?!well-known)\">"), "dotfiles (.env, .git) denied");
    }

    #[test]
    fn old_templates_get_the_vhost_include() {
        let nginx = web("nginx", "events {}\nhttp {\n    server {\n        listen 80;\n    }\n}\n");
        let mut nginx = InstalledModule { config_templates: BTreeMap::from([("nginx.conf".into(), nginx.config_templates["main.conf"].clone())]), ..nginx };
        let migrated = with_vhost_include(&nginx).expect("nginx migrated");
        let tpl = &migrated.config_templates["nginx.conf"];
        assert!(supports_vhosts(&migrated));
        assert!(tpl.contains("    }\n\n    # Projects"), "inside http, after the server: {tpl}");
        assert!(tpl.trim_end().ends_with("include \"{{conf}}/vhosts/*.conf\";\n}"), "{tpl}");
        assert!(with_vhost_include(&migrated).is_none(), "idempotent");

        nginx.config_templates.insert("nginx.conf".into(), "no braces".into());
        assert!(with_vhost_include(&nginx).is_none(), "unknown shape left alone");

        let apache = web("apache", "Listen 82");
        let apache = InstalledModule { config_templates: BTreeMap::from([("httpd.conf".into(), "Listen 82".into())]), ..apache };
        let migrated = with_vhost_include(&apache).expect("apache migrated");
        assert!(migrated.config_templates["httpd.conf"].ends_with("IncludeOptional \"{{conf}}/vhosts/*.conf\"\n"));
        assert!(with_vhost_include(&web("php", "x")).is_none());
    }

    #[test]
    fn unsafe_paths_are_rejected() {
        assert!(check_conf_path("/home/a/www").is_ok());
        assert!(check_conf_path("/home/a\"; evil").is_err());
        assert!(check_conf_path("/home/$host").is_err());
        assert!(check_conf_path("/home/a\nb").is_err());
    }
}
